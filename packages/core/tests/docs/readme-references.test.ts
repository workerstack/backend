/**
 * Core's README is the docs pack's: `repo sync` builds it from packages/core/references/, one section per file in the
 * INDEX's order, so the guide's text lives there and the README is never edited by hand. This file holds the README to
 * that layout and the INDEX to every reference; that the README is current is `repo check`'s.
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { REPO } from "./docs-blocks.ts";

const REFS = "packages/core/references";
const INDEX = "INDEX.md";
const HEADER = "<!-- @generated by @workerstack/repo -->";
const CONTENTS = "## Contents";
const SECTION = "## ";
const FENCE = /^\s*(?:```|~~~)/u;
const LISTED = /^- `([^`]+\.md)`: /gmu;

function read(rel: string): string {
  return readFileSync(join(REPO, rel), "utf8");
}

/** The `.md` files a references/ INDEX lists, in its order (its `repo:refs` lines). */
export function indexedRefs(index: string): string[] {
  return [...index.matchAll(LISTED)].flatMap(([, file]) => (file === undefined ? [] : [file]));
}

/** A markdown file's first H1, fenced blocks aside; null when it has none. */
export function titleOf(markdown: string): string | null {
  let isFenced = false;

  for (const line of markdown.split("\n")) {
    if (FENCE.test(line)) isFenced = !isFenced;
    else if (!isFenced && line.startsWith("# ")) return line.slice(2).trim();
  }

  return null;
}

/** The README's section titles: its `##` headings but the contents. */
function sectionsOf(readme: string): string[] {
  return readme
    .split("\n")
    .filter((line) => line.startsWith(SECTION) && line !== CONTENTS)
    .map((line) => line.slice(SECTION.length));
}

describe("core's README is the docs pack's, built from its references", () => {
  it("carries the generated header and one section per reference, in the INDEX's order", () => {
    const readme = read("packages/core/README.md");
    const listed = indexedRefs(read(`${REFS}/${INDEX}`));
    const titles = listed.map((file) => titleOf(read(`${REFS}/${file}`)));

    expect([readme.startsWith(HEADER), listed.length > 20, sectionsOf(readme)]).toStrictEqual([true, true, titles]);
  });

  it("lists every reference file in the INDEX, so none is left out of the README", () => {
    const listed = indexedRefs(read(`${REFS}/${INDEX}`));
    const files = readdirSync(join(REPO, REFS)).filter((file) => file.endsWith(".md") && file !== INDEX);

    expect(files.filter((file) => !listed.includes(file))).toStrictEqual([]);
  });

  it("reads an INDEX's files and a page's title past its fences", () => {
    expect(indexedRefs("# x\n\n- `a.md`: A\n- `b.md`: B\n- [c](c.md): no\n")).toStrictEqual(["a.md", "b.md"]);
    expect(titleOf("---\ndescription: d\n---\n\n```sh\n# a comment\n```\n\n# Title\n")).toBe("Title");
    expect(titleOf("no heading\n")).toBeNull();
  });
});
